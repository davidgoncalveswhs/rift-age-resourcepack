def hexrgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def icon(shape, pal, sparkle=False, seed=0):
    rows = [r for r in G[shape].strip("\n").split("\n")]
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), (shape, [len(r) for r in rows])
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    p = PAL[pal]
    rnd = random.Random(seed)
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch == ".":
                continue
            c = hexrgb(p[ch])
            if ch in "bd" and rnd.random() < 0.12:  # a little texture
                c = tuple(max(0, min(255, v + rnd.choice((-12, 10)))) for v in c)
            img.putpixel((x, y), c + (255,))
    if sparkle:
        a = hexrgb(p["a"])
        for (x, y) in [(xx, yy) for yy in range(16) for xx in range(16)]:
            if img.getpixel((x, y))[3] and rows[y][x] == "b" and rnd.random() < 0.05:
                img.putpixel((x, y), a + (255,))
    return img


# ---------------------------------------------------------------- 64x32 armor layers

def _face(img, x0, y0, w, h, pal, rnd, pattern=None):
    p = {k: hexrgb(v) for k, v in PAL[pal].items()}
    for y in range(h):
        for x in range(w):
            edge = x == 0 or y == 0 or x == w - 1 or y == h - 1
            c = p["d"] if edge else p["b"]
            if not edge and (x == 1 or y == 1):
                c = p["l"]
            if not edge and rnd.random() < 0.10:
                c = tuple(max(0, min(255, v + rnd.choice((-14, 12)))) for v in c)
            img.putpixel((x0 + x, y0 + y), c + (255,))
    if pattern:
        pattern(img, x0, y0, w, h, p)


def _box(img, u, v, w, h, d, pal, rnd, front=None, all_faces=None):
    """Minecraft cuboid UV: top/bottom on the first row, then right, front, left, back."""
    _face(img, u + d, v, w, d, pal, rnd, all_faces)               # top
    _face(img, u + d + w, v, w, d, pal, rnd, all_faces)           # bottom
    _face(img, u, v + d, d, h, pal, rnd, all_faces)               # right
    _face(img, u + d, v + d, w, h, pal, rnd, front or all_faces)  # front
    _face(img, u + d + w, v + d, d, h, pal, rnd, all_faces)       # left
    _face(img, u + d + w + d, v + d, w, h, pal, rnd, all_faces)   # back


def _gem(img, x0, y0, w, h, p):  # a glowing gem in the middle of a face
    cx, cy = x0 + w // 2, y0 + h // 2
    for (dx, dy, k) in [(0, -1, "l"), (-1, 0, "a"), (0, 0, "a"), (1, 0, "g"), (0, 1, "g"), (-1, -1, "o"), (1, -1, "o")]:
        if 0 <= cy + dy < 32:
            img.putpixel((cx + dx - 1 if w % 2 == 0 else cx + dx, cy + dy), p[k] + (255,))


def _trim(img, x0, y0, w, h, p):  # accent line along the top and bottom
    for x in range(1, w - 1):
        img.putpixel((x0 + x, y0 + 1), p["a"] + (255,))
        if h > 3:
            img.putpixel((x0 + x, y0 + h - 2), p["g"] + (255,))


def _visor(img, x0, y0, w, h, p):  # dark eye slit
    y = y0 + h // 2
    for x in range(1, w - 1):
        img.putpixel((x0 + x, y), p["o"] + (255,))
    img.putpixel((x0 + w // 2, y0 + 2), p["a"] + (255,))
    img.putpixel((x0 + w // 2 - 1, y0 + 2), p["a"] + (255,))


def armor_layers(pal, seed=1):
    rnd = random.Random(seed)
    l1 = Image.new("RGBA", (64, 32), (0, 0, 0, 0))
    _box(l1, 0, 0, 8, 8, 8, pal, rnd, front=_visor, all_faces=_trim)          # helmet (head)
    _box(l1, 16, 16, 8, 12, 4, pal, rnd, front=lambda i, x, y, w, h, p: (_trim(i, x, y, w, h, p), _gem(i, x, y, w, h, p)))  # chest
    _box(l1, 40, 16, 4, 12, 4, pal, rnd, all_faces=_trim)                    # arms
    # boots: only the lower part of the leg box
    leg = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    _box(leg, 0, 0, 4, 12, 4, pal, rnd, all_faces=_trim)
    for y in range(16):
        for x in range(16):
            if y >= 4 + 6 or y < 4 and x >= 4:  # side faces start at row 4; keep rows 10-15 (the boot) and the sole
                px = leg.getpixel((x, y))
                if y >= 10 or (y < 4 and 8 <= x < 12):
                    l1.putpixel((x, 16 + y), px)
    l2 = Image.new("RGBA", (64, 32), (0, 0, 0, 0))
    _box(l2, 0, 16, 4, 12, 4, pal, rnd, all_faces=_trim)                     # legs
    belt = Image.new("RGBA", (24, 16), (0, 0, 0, 0))
    _box(belt, 0, 0, 8, 12, 4, pal, rnd, all_faces=_trim)
    for y in range(4, 16):
        for x in range(24):
            if y >= 11:  # lower body rows: the belt
                l2.putpixel((16 + x, 16 + y), belt.getpixel((x, y)))
    return l1, l2
